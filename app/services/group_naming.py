"""
"Регион УК", "ПП" и "Увеличители" — три виртуальные группы, на которые
excel_parsing.py делит группу "ГРУППА: операторы без супервизора"
(сборная солянка разных ролей: ЗДР/ПП/Увеличители вперемешку).
Разделение — по префиксу ФИО: "ЗДР" -> "Регион УК", "ПП" -> "ПП",
"Увеличители" -> "Увеличители". Раньше "ПП" и "Увеличители" были одной
общей группой "Выходы на Пики" — по прямому запросу заказчика разделены
на две отдельные группы (у каждой свой рейтинг/ЛГ, но те же особые
правила, что были у общей "Пики", см. ниже). Все три группы — НЕ
настоящие супервайзеры: исключаются из сравнения/рейтинга супервайзеров
между собой, но участвуют в основном рейтинге по группам (включая ЛГ
внутри своей "группы") как обычно.

"ПП" и "Увеличители" (бывшая объединённая "Пики") дополнительно
исключаются из часовой ставки в формуле ЗП (см. services/salary.py) —
это тоже общий признак PEAKS_GROUP_RE, а не что-то специфичное для
одной из двух подгрупп.

Здесь — общая логика распознавания и отображаемое название группы,
используемая и при расчёте недельного рейтинга (weekly_rating.py), и в
ведомости ЗП (payroll.py), и в дашбордах (dashboards.py).
"""
from __future__ import annotations

import re

REGION_UK_GROUP_RE = re.compile(r"операторы\s+без\s+супервизора", re.IGNORECASE)
PEAKS_PP_GROUP_RE = re.compile(r"операторы\s+без\s+супервизора\s*\[Пики-ПП\]", re.IGNORECASE)
PEAKS_UVELICHITELI_GROUP_RE = re.compile(r"операторы\s+без\s+супервизора\s*\[Пики-Увеличители\]", re.IGNORECASE)
# Общий признак ОБЕИХ подгрупп бывшей "Пики" — используется там, где
# правило одинаково для "ПП" и "Увеличители" (исключение из часовой
# ставки в ЗП, см. salary.py). НЕ путать с REGION_UK_GROUP_RE — тот
# матчит ещё и "Регион УК" (голое "операторы без супервизора").
PEAKS_GROUP_RE = re.compile(
    r"операторы\s+без\s+супервизора\s*\[Пики-(?:ПП|Увеличители)\]", re.IGNORECASE
)
PEAKS_PP_SUFFIX = " [Пики-ПП]"
PEAKS_UVELICHITELI_SUFFIX = " [Пики-Увеличители]"

# cleanSupervisorName() из старой JS-версии — префиксы вида
# "Супервайзер - "/"Супервайзер.- "/"Супервизор " перед именем обычного
# супервайзера. Порядок важен: сначала более длинный "Супервайзер...".
_SUPERVISOR_PREFIX_RE = re.compile(r"^Супервайзер[.\-–\s]+", re.IGNORECASE)
_SUPERVIZOR_PREFIX_RE = re.compile(r"^Супервизор\s*", re.IGNORECASE)

# Тир ЛК жёстко завязан на 5 стандартных категорий (см. weekly_rating.py) —
# "Регион УК" (Уволенные/Нераспределенные) считается только по этим трём,
# без канала и % ошибок. Места по остальным категориям всё равно
# считаются и хранятся (нужны тиру ЛК и для отображения в таблице) —
# урезается только то, что идёт в SUM для total_score.
REGION_UK_SCORE_KEYS = {"c1", "lk", "time"}

# "ПП"/"Увеличители" (бывшая общая "Пики") — наоборот, total_score ТОЛЬКО
# по каналу, остальные 4 категории считаются/показываются как обычно, но
# не входят в сумму. weekly_rating.py применяет урезание к employee,
# чей supervisor совпадает с PEAKS_GROUP_RE (обе подгруппы — общий признак
# бывшей "Пики", см. докстринг PEAKS_GROUP_RE выше).
PEAKS_SCORE_KEYS = {"channel"}

# Сектор №1 (4 обычных группы супервайзеров, объединённые по запросу
# заказчика для отдельного руководителя сектора) — точные строки
# supervisor, найдены по реальным данным (см. историю запроса создания
# Сектора 1), НЕ вычисляются по паттерну/префиксу, в отличие от Региона
# УК/Пиков. Категория "ЛК" получает вес 0 в total_score для ВСЕХ
# сотрудников этих групп, КРОМЕ трёх исключений ниже — у них ЛК остаётся
# с обычным весом (1.5), как у всех остальных сотрудников компании. Места
# по ЛК (lk_place) всё равно считаются и показываются как обычно — тот же
# принцип "урезаем только SUM", что у REGION_UK_SCORE_KEYS/PEAKS_SCORE_KEYS
# выше, просто здесь исключается ОДНА категория ("lk"), а не оставляется
# только одна, и решение принимается по конкретному сотруднику, а не по
# всей группе сразу (3 человека — исключение ИЗ правила, не подпадают
# под урезание, весь остальной состав этих 4 групп — подпадает).
SECTOR_1_SUPERVISORS = frozenset({
    "Супервайзер - Болотов Дмитрий Александрович",
    "Супервайзер - Владыкин Сергей Александрович",
    "Супервайзер - Гулуа Анна Эдуардовна",
    "Супервайзер - Потапова Алина Дамировна",
})

# ФИО — точно как в реальном файле выгрузки (сокращённая форма с
# префиксом "ЗДР ЛК", а не полное ФИО) — сверено вживую перед вводом.
SECTOR_1_LK_WEIGHT_EXCEPTIONS_FIO = frozenset({
    "ЗДР ЛК Ремизов А. Г.",
    "ЗДР ЛК Борисенко Н. В.",
    "ЗДР ЛК Шайдуров А. В.",
})

# Сектор №1 — по прямому запросу заказчика диапазон коэффициентов ЛГ уже,
# чем у обычных групп: не 10 тиров (1.4...0.25), а 5 тиров (1.3...1.0).
# Используется вместо TIER_COEFFICIENTS/настроенной через /ladder-tiers
# таблицы — см. services/ladder_groups.py::assign_tier_coefficients/
# assign_novice_coefficients, где для supervisor из SECTOR_1_SUPERVISORS
# эта таблица подставляется вместо обычной (и число тиров тоже 5, не 10 —
# длина этого списка).
SECTOR_1_TIER_COEFFICIENTS = [1.3, 1.2, 1.1, 1.05, 1.0]


def sector1_zeroes_lk_weight(supervisor: str | None, fio: str | None) -> bool:
    """True, если этому сотруднику нужно урезать ЛК из total_score —
    сотрудник одной из 4 групп Сектора 1, и он НЕ входит в 3 исключения."""
    return bool(supervisor) and supervisor in SECTOR_1_SUPERVISORS and fio not in SECTOR_1_LK_WEIGHT_EXCEPTIONS_FIO


# Сектор №2 (3 обычные группы, отдельный руководитель — Сорокин Никита) —
# точные строки supervisor, найдены по реальным данным, как и для
# Сектора 1. В ОТЛИЧИЕ от Сектора 1: ЛК считается ОБЫЧНО (вес 1.5, без
# исключений/форсированного 1-го места) — по прямому запросу заказчика
# урезание веса ЛК для Сектора 2 не нужно. Общее с Сектором 1 — только
# 2 правила: статус "Новичок" не исключает из официального места (см.
# excel_parsing.py::is_na_row) и суженный диапазон ЛГ (см.
# SECTOR_2_TIER_COEFFICIENTS ниже, те же 5 тиров 1.3...1.0, что у Сектора 1).
SECTOR_2_SUPERVISORS = frozenset({
    "Супервайзер - Курилова Марина Вадимовна",
    "Супервайзер - Бровкова Елена Александровна",
    "Супервайзер - Басараб Станислав Федорович",
})
SECTOR_2_TIER_COEFFICIENTS = [1.3, 1.2, 1.1, 1.05, 1.0]


def is_region_uk_or_peaks_supervisor(supervisor: str | None) -> bool:
    """True для ВСЕХ ТРЁХ виртуальных групп (совпадает по общему префиксу
    "операторы без супервизора" — для "Регион УК", "ПП" и "Увеличители",
    у двух последних supervisor заканчивается на " [Пики-ПП]"/
    " [Пики-Увеличители]")."""
    return bool(supervisor) and bool(REGION_UK_GROUP_RE.search(supervisor))


def clean_supervisor_name(name: str | None) -> str:
    """Убирает префикс "Супервайзер - "/"Супервайзер.- "/"Супервизор " перед
    именем обычного супервайзера. Точный перенос cleanSupervisorName()."""
    name = name or ""
    name = _SUPERVISOR_PREFIX_RE.sub("", name)
    name = _SUPERVIZOR_PREFIX_RE.sub("", name)
    return name.strip()


def display_group_name(supervisor: str | None) -> str:
    """Человекочитаемое название группы для API-ответов/фронтенда."""
    if not supervisor:
        return ""
    if PEAKS_PP_GROUP_RE.search(supervisor):
        return "ПП"
    if PEAKS_UVELICHITELI_GROUP_RE.search(supervisor):
        return "Увеличители"
    if REGION_UK_GROUP_RE.search(supervisor):
        # Отображаемое название переименовано ("Регион УК" -> "Уволенные/
        # Нераспределенные") — сама группа/регулярка/особое поведение
        # (низ списка, исключение из рейтинга супервайзеров, урезанный
        # набор категорий) не изменились, поменялась только эта строка.
        return "Уволенные/Нераспределенные"
    return clean_supervisor_name(supervisor)
