"""
Тир канала (Радио+ТВ / Интернет) — структурно СИММЕТРИЧЕН тиру ЛК
(tier_lk.py: тир A/Б/В по картам+конверсии), но НЕ использует места
других категорий вообще — только свои карточки/конверсию/сумму с
контакта. Это делает тир канала полностью самостоятельным (в отличие
от тира ЛК, который зависит от него) и снимает саму возможность
циклической зависимости между ними: тир канала считается ПЕРВЫМ,
окончательно, до всех остальных категорий; тир ЛК считается ПОСЛЕ и
использует уже готовое (финальное) место по каналу, см.
compute_weekly_rating.

Тир A (лучший) — карточки > 0 И конверсия > 0%: обычный спортивный
    ранг по "сумма с контакта" (больше = лучше). Одинаковые места при
    равных суммах — норма (обычный спортивный ранг, как везде).
Тир Б (средний) — карточек 0 (конверсии тогда взяться неоткуда,
    поэтому проверяется через "иначе", как в tier_lk.py): ВСЕ такие
    сотрудники делят ОДНО место, сразу после тира A (idxA.length + 1).
    Это НЕ среднее по категориям (в отличие от тира ЛК) — просто
    фиксированная позиция.
Тир В (худший) — карточки > 0, но конверсия == 0% (карточки потрачены
    впустую): ранжируется по количеству карточек — ЧЕМ БОЛЬШЕ впустую
    потраченных карт, ТЕМ ХУЖЕ место. Места считаются от первого
    свободного места ПОСЛЕ тира Б: т.к. тир Б — это одна связка
    одинаковых мест размером idxB.length, следующее свободное место
    (по обычной логике "пропуска мест при ничьей", как rankDesc/
    rank_standard везде в проекте) = idxA.length + idxB.length + 1.
"""
from __future__ import annotations

from app.services.rating_engine import rank_standard


def compute_tiered_channel_places(items: list[dict]) -> list[float]:
    """
    items: строки за неделю; каждая должна содержать сырые
    ch_cards/ch_conv/ch_per_contact. В отличие от тира ЛК, места других
    категорий (c1/lk/time/errors) тут НЕ нужны — тир канала ни от чего,
    кроме собственных карточек/конверсии/суммы с контакта, не зависит.

    Возвращает список мест по категории "канал", в том же порядке, что
    items: тир A — целые числа 1..|A| (спортивный ранг, ties делят
    место); тир Б — все получают ОДНО и то же место idxA.length + 1;
    тир В — целые числа начиная с idxA.length + idxB.length + 1,
    ранжируются по кол-ву карточек (больше карточек = хуже место).
    """
    idx_a: list[int] = []
    idx_b: list[int] = []
    idx_c: list[int] = []
    for i, e in enumerate(items):
        cards = e.get("ch_cards") or 0
        conv = e.get("ch_conv") or 0
        if cards > 0 and conv > 0:
            idx_a.append(i)
        elif cards > 0 and conv == 0:
            idx_c.append(i)
        else:
            idx_b.append(i)  # карточек 0 (конверсия в этом случае тоже 0)

    places: list[float] = [1.0] * len(items)

    pc_a = [items[i]["ch_per_contact"] for i in idx_a]
    for i in idx_a:
        places[i] = float(rank_standard(pc_a, items[i]["ch_per_contact"], "desc"))

    b_place = float(len(idx_a) + 1)
    for i in idx_b:
        places[i] = b_place

    cards_c = [items[i]["ch_cards"] for i in idx_c]
    base_c = len(idx_a) + len(idx_b)
    for i in idx_c:
        places[i] = float(base_c + rank_standard(cards_c, items[i]["ch_cards"], "asc"))

    return places
